"""
Creates the Lighter tool (a disposable-style lighter that lights fireplaces: properties.lights_fires) in headless Blender: a small
procedural model, its manifest and README. The icon is rendered afterwards from the model:
    python tools/render_icon_from_model.py assets/tools/tool_lighter/tool_lighter.glb assets/tools/tool_lighter/tool_lighter.png

    blender --background --python tools/make_lighter.py
"""
import copy
import json
import os
import sys

import bpy

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import make_structure_stages as base  # noqa: E402

ROOT = base.ROOT
ID = 'tool_lighter'


def main():
    folder = os.path.join(ROOT, 'assets', 'tools', ID)
    os.makedirs(folder, exist_ok=True)
    for o in list(bpy.data.objects):
        bpy.data.objects.remove(o, do_unlink=True)
    b = base.Builder(ID)
    body = base.material('LighterBody', (0.78, 0.12, 0.1), 0.35)
    metal = base.material('LighterMetal', (0.75, 0.76, 0.78), 0.3)
    dark = base.material('LighterDark', (0.1, 0.1, 0.11), 0.6)
    # pocket size: 0.025 x 0.012 x 0.085 m, lying flat so the icon shows it from the side
    b.box(-0.0425, 0.0, -0.006, 0.006, 0.0, 0.025, body)                 # the fuel body
    b.box(-0.0425, -0.0415, -0.0065, 0.0065, 0.0, 0.025, dark)           # the base cap
    b.box(0.0, 0.025, -0.0055, 0.0055, 0.004, 0.025, metal)              # the metal hood
    b.box(0.0, 0.025, -0.0055, 0.0055, 0.025, 0.0275, metal)             # the hood's top
    b.box(0.006, 0.012, -0.0045, 0.0045, 0.0275, 0.032, dark)            # the striker wheel housing
    b.box(0.014, 0.0185, -0.004, 0.004, 0.0275, 0.0345, metal)           # the flame guard
    obj = b.finish()
    bpy.ops.object.select_all(action='DESELECT')
    obj.select_set(True)
    bpy.context.view_layer.objects.active = obj
    out = os.path.join(folder, ID + '.glb')
    bpy.ops.export_scene.gltf(filepath=out, export_format='GLB', use_selection=True, export_yup=True)
    tris = sum(len(p.vertices) - 2 for p in obj.data.polygons)

    tmpl = json.load(open(os.path.join(ROOT, 'assets', 'tools', 'tool_hammer_claw', 'tool_hammer_claw.json'), encoding='utf-8'))
    m = copy.deepcopy(tmpl)
    m['id'] = ID
    m['name'] = 'Lighter'
    m['icon'] = ID + '.png'
    m['description'] = 'A pocket lighter. Right click a fireplace with firewood in it to light the fire. It is not used up.'
    p = m['properties']
    p.update({'weight_kg': 0.05, 'max_stack_size': 1, 'base_value': 6, 'is_buyable': True, 'stores': ['depot'], 'sale_unit': 'ea',
              'lights_fires': True, 'footprint': '0.03m W x 0.09m D x 0.035m H'})
    m['models'] = [{'file': ID + '.glb', 'format': 'glb', 'dimensions_m': {'x': 0.085, 'y': 0.035, 'z': 0.012}, 'triangles': tris}]
    m['category_fields'] = {'dimensions_m': {'width': 0.012, 'depth': 0.085, 'height': 0.035}, 'fuel_type': 'butane',
                            'fuel_consumption_l_per_min': 0, 'power_draw_w': 0, 'tank_capacity_l': 0}
    json.dump(m, open(os.path.join(folder, ID + '.json'), 'w', encoding='utf-8'), indent=2)
    open(os.path.join(folder, 'README.md'), 'w', encoding='utf-8').write(
        '# Lighter\n\nA pocket lighter: right click a fireplace that has firewood in it to light the fire (properties.lights_fires). '
        'Not used up.\n\nGenerated by tools/make_lighter.py (procedural model, %d triangles).\n' % tris)
    print('lighter', tris)


if __name__ == '__main__':
    main()
