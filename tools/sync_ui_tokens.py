"""Copy the design tokens in HUDTree/UITokens.uss into the :root block of each document's stylesheet.

Unity resolves var() per document, so every document that uses tokens needs them in its own :root. The copy lives
between the markers below and is replaced on every run. Run after editing UITokens.uss:

    python tools/sync_ui_tokens.py

With --apply-literals it also replaces exact literal colors (and 'border-radius: 0') in the stylesheets with the
matching tokens, once. Colors written as rgba() and one-off oranges are left alone.
"""
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'Homesteader', 'Assets', 'Resources', 'HUDTree')
TOKENS = os.path.join(ROOT, 'UITokens.uss')
TARGETS = ['HudUI.uss', 'WelcomeMenu.uss']
LITERAL_TARGETS = ['HudUI.uss', 'WelcomeMenu.uss', 'PhoneUI.uss', 'ResourcesBar.uss', 'SpeedControls.uss',
                   'TimeAndDate.uss', 'ToolbarSlots.uss', 'Vitals.uss']
BEGIN = '/* BEGIN UI TOKENS (generated by tools/sync_ui_tokens.py from UITokens.uss; do not edit here) */'
END = '/* END UI TOKENS */'

LITERALS = {
    'rgb(18, 22, 29)': 'var(--c-ink)',
    'rgb(26, 33, 43)': 'var(--c-well)',
    'rgb(29, 36, 46)': 'var(--c-field)',
    'rgb(43, 52, 66)': 'var(--c-panel)',
    'rgb(61, 74, 92)': 'var(--c-raised)',
    'rgb(92, 102, 117)': 'var(--c-rim)',
    'rgb(238, 242, 246)': 'var(--c-text)',
    'rgb(255, 255, 255)': 'var(--c-text-strong)',
    'rgb(139, 150, 165)': 'var(--c-muted)',
    'rgb(224, 138, 60)': 'var(--c-accent)',
    'rgb(241, 170, 104)': 'var(--c-accent-hi)',
    'rgb(188, 112, 40)': 'var(--c-accent-lo)',
    'rgb(198, 32, 38)': 'var(--c-danger)',
    'rgb(228, 92, 96)': 'var(--c-danger-text)',
    'rgb(54, 196, 177)': 'var(--c-secondary)',
    'rgb(39, 135, 122)': 'var(--c-secondary-lo)',
}


def read(p):
    with open(p, encoding='utf-8', newline='') as f:
        raw = f.read()
    nl = '\r\n' if '\r\n' in raw else '\n'
    return raw.replace('\r\n', '\n'), nl


def write(p, s, nl):
    with open(p + '.new', 'w', encoding='utf-8', newline='') as f:
        f.write(s.replace('\n', nl))
    os.replace(p + '.new', p)


def token_lines():
    s, _ = read(TOKENS)
    m = re.search(r':root\s*\{(.*)\}\s*$', s, re.S)
    lines = [ln.rstrip() for ln in m.group(1).split('\n')]
    return '\n'.join(ln for ln in lines if ln.strip()) + '\n'


def strip_block(s):
    return re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END) + r'\n?', '', s, flags=re.S)


def sync():
    block = BEGIN + '\n' + token_lines() + END + '\n'
    for name in TARGETS:
        p = os.path.join(ROOT, name)
        s, nl = read(p)
        s = strip_block(s)
        i = s.index(':root {') + len(':root {')
        s = s[:i] + '\n' + block.rstrip('\n') + '\n' + s[i:].lstrip('\n') if False else s[:i] + '\n' + block + s[i:].lstrip('\n')
        write(p, s, nl)
        print('tokens synced into', name)


def apply_literals():
    for name in LITERAL_TARGETS:
        p = os.path.join(ROOT, name)
        s, nl = read(p)
        # keep the token blocks (which hold the literals) out of the replacement
        parts = re.split('(' + re.escape(BEGIN) + r'.*?' + re.escape(END) + ')', s, flags=re.S)
        out = []
        n = 0
        for part in parts:
            if part.startswith(BEGIN):
                out.append(part)
                continue
            for lit, var in LITERALS.items():
                n += part.count(lit)
                part = part.replace(lit, var)
            n += len(re.findall(r'border-radius:\s*0(px)?\s*;', part))
            part = re.sub(r'border-radius:\s*0(px)?\s*;', 'border-radius: var(--r);', part)
            out.append(part)
        write(p, ''.join(out), nl)
        print(name, 'literals replaced:', n)


if __name__ == '__main__':
    sync()
    if '--apply-literals' in sys.argv:
        apply_literals()
