"""One-time migration: the old per-window button classes take their look from the shared button groups.

For every mapped class the visual declarations (colors, font, radius, text align) and its :hover/:active/variant rules
are removed from the feature stylesheets (layout such as width, height and margin stays), and the class is added to a
shared group in UIControls.uss (between the BEGIN/END BUTTON GROUPS markers, regenerated on every run). UXML and C#
class names do not change.

    python tools/ui_migrate_buttons.py
"""
import os
import re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'Homesteader', 'Assets', 'Resources', 'HUDTree')
FEATURE = ['HudUI.uss', 'PhoneUI.uss', 'WelcomeMenu.uss']
BEGIN = '/* BEGIN BUTTON GROUPS (generated by tools/ui_migrate_buttons.py; do not edit here) */'
END = '/* END BUTTON GROUPS */'

GROUPS = {
    'neutral': ['hs-btn', 'action-btn', 'action-btn--secondary', 'welcome-btn', 'settings-action-btn', 'settings-footer-btn',
                'bank-action-btn', 'admin-chip-btn', 'admin-step-btn', 'admin-vital-zero-btn', 'admin-set-btn',
                'mods-category-back-btn', 'controls-key-btn', 'steadify-popout-btn', 'header-settings-btn',
                'almanac-tab-btn', 'mod-toggle-btn'],
    'primary': ['hs-btn--primary', 'action-btn--primary', 'welcome-btn--primary', 'store-item-buy-btn',
                'controls-key-btn--capturing', 'container-panel-btn'],
    'danger': ['hs-btn--danger', 'welcome-btn--exit', 'mod-toggle-btn--disabled'],
    'teal': ['hs-btn--teal', 'admin-header-assets-btn', 'admin-action-btn', 'mod-toggle-btn--enabled',
             'steadify-shuffle-all-btn'],
    'ghost': ['hs-btn--ghost', 'phone-back-btn', 'market-tab-btn', 'settings-nav-btn'],
    'active': ['hs-btn--active', 'admin-chip-btn--active', 'market-tab-btn--active', 'almanac-tab-btn--active',
               'settings-nav-btn--active'],
}
MAPPED = {c for g in GROUPS.values() for c in g if c not in ('hs-btn', 'hs-btn--primary', 'hs-btn--danger', 'hs-btn--teal',
                                                              'hs-btn--ghost', 'hs-btn--active')}
VISUAL = re.compile(r'^\s*(background-color|border-color|border-radius|color|-unity-font|-unity-font-style|letter-spacing|'
                    r'-unity-text-align|border-left-color|border-top-color|border-bottom-color|border-right-color)\s*:')


def sel(names, suffix=''):
    return ',\n'.join('.' + n + suffix for n in names)


def groups_css():
    n = GROUPS
    o = [BEGIN]
    o.append(sel(n['neutral']) + ' {\n    border-radius: var(--r);\n    -unity-text-align: middle-center;\n    padding-top: 0;\n    padding-bottom: 0;\n    background-color: var(--c-panel);\n    border-color: var(--c-raised);\n'
             '    color: var(--c-text);\n    -unity-font: var(--font-medium);\n'
             '    -unity-text-align: middle-center;\n}\n')
    o.append(sel(n['neutral'], ':hover') + ' {\n    background-color: var(--c-raised);\n    border-color: var(--c-rim);\n'
             '    color: var(--c-text-strong);\n}\n')
    o.append(sel(n['neutral'], ':active') + ' {\n    background-color: var(--c-well);\n}\n')
    o.append(sel(n['primary']) + ' {\n    border-radius: var(--r);\n    -unity-text-align: middle-center;\n    padding-top: 0;\n    padding-bottom: 0;\n    background-color: var(--c-accent);\n    border-color: var(--c-accent-hi);\n'
             '    color: var(--c-ink);\n    -unity-font: var(--font-bold);\n}\n')
    o.append(sel(n['primary'], ':hover') + ' {\n    background-color: var(--c-accent-hi);\n    border-color: var(--c-accent-hi);\n'
             '    color: var(--c-ink);\n}\n')
    o.append(sel(n['primary'], ':active') + ' {\n    background-color: var(--c-accent-lo);\n}\n')
    o.append(sel(n['danger']) + ' {\n    border-radius: var(--r);\n    -unity-text-align: middle-center;\n    padding-top: 0;\n    padding-bottom: 0;\n    background-color: rgba(18, 22, 29, 0);\n    border-color: rgba(227, 83, 88, 0.4);\n'
             '    color: var(--c-danger-text);\n}\n')
    o.append(sel(n['danger'], ':hover') + ' {\n    background-color: var(--c-danger);\n    border-color: var(--c-danger);\n'
             '    color: var(--c-text-strong);\n}\n')
    o.append(sel(n['teal']) + ' {\n    border-radius: var(--r);\n    -unity-text-align: middle-center;\n    padding-top: 0;\n    padding-bottom: 0;\n    background-color: rgba(54, 196, 177, 0.14);\n    border-color: var(--c-secondary-lo);\n'
             '    color: var(--c-secondary-hi);\n    -unity-font: var(--font-bold);\n}\n')
    o.append(sel(n['teal'], ':hover') + ' {\n    background-color: var(--c-secondary-lo);\n    border-color: var(--c-secondary);\n'
             '    color: var(--c-text-strong);\n}\n')
    o.append(sel(n['ghost']) + ' {\n    border-radius: var(--r);\n    -unity-text-align: middle-center;\n    padding-top: 0;\n    padding-bottom: 0;\n    background-color: rgba(18, 22, 29, 0);\n    border-color: rgba(18, 22, 29, 0);\n'
             '    color: var(--c-muted);\n}\n')
    o.append(sel(n['ghost'], ':hover') + ' {\n    background-color: var(--c-raised);\n    border-color: rgba(18, 22, 29, 0);\n'
             '    color: var(--c-text-strong);\n}\n')
    o.append(sel(n['active']) + ' {\n    border-radius: var(--r);\n    -unity-text-align: middle-center;\n    padding-top: 0;\n    padding-bottom: 0;\n    background-color: rgba(224, 138, 60, 0.22);\n    border-color: var(--c-accent-hi);\n'
             '    color: rgb(255, 219, 185);\n    -unity-font: var(--font-bold);\n}\n')
    o.append(END)
    return '\n'.join(o) + '\n'


def read(p):
    raw = open(p, encoding='utf-8', newline='').read()
    return raw.replace('\r\n', '\n'), ('\r\n' if '\r\n' in raw else '\n')


def write(p, s, nl):
    open(p + '.new', 'w', encoding='utf-8', newline='').write(s.replace('\n', nl))
    os.replace(p + '.new', p)


def classes_of(selector):
    return set(re.findall(r'\.([A-Za-z0-9_-]+)', selector))


def process(s):
    comments = []

    def stash(m):
        comments.append(m.group(0))
        return '\x00%d\x00' % (len(comments) - 1)
    t = re.sub(r'/\*.*?\*/', stash, s, flags=re.S)
    out, pos, removed, stripped = [], 0, 0, 0
    for m in re.finditer(r'([^{}]*?)\{([^{}]*)\}', t):
        selector, body = m.group(1), m.group(2)
        cls = classes_of(selector)
        hit = cls & MAPPED
        out.append(t[pos:m.start()])
        pos = m.end()
        if not hit or cls - MAPPED - {'unity-button'}:
            out.append(m.group(0))
            continue
        pseudo = re.search(r':(hover|active|focus)', selector)
        variant = any('--' in c for c in hit)
        if pseudo or variant:
            removed += 1
            # drop the rule and the blank line after it
            continue
        lines = body.split('\n')
        keep = [ln for ln in lines if not VISUAL.match(ln)]
        stripped += len(lines) - len(keep)
        out.append(selector + '{' + '\n'.join(keep) + '}')
    out.append(t[pos:])
    t = ''.join(out)
    t = re.sub(r'\n{3,}', '\n\n', t)
    t = re.sub(r'\x00(\d+)\x00', lambda m: comments[int(m.group(1))], t)
    return t, removed, stripped


def main():
    for name in FEATURE:
        p = os.path.join(ROOT, name)
        s, nl = read(p)
        s, removed, stripped = process(s)
        write(p, s, nl)
        print(name, 'rules removed:', removed, 'visual lines removed:', stripped)
    p = os.path.join(ROOT, 'UIControls.uss')
    s, nl = read(p)
    s = re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END) + r'\n?', '', s, flags=re.S)
    marker = '/* ============================================================ checkbox'
    assert marker in s
    s = s.replace(marker, groups_css() + '\n' + marker, 1)
    write(p, s, nl)
    print('button groups written to UIControls.uss')


if __name__ == '__main__':
    main()
