using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using Homesteader.Generation;
using UnityEngine;

namespace Homesteader.Modding
{
    /// <summary>
    /// Startup entry point for the mod system. Drop this on a GameObject in the
    /// boot scene (it self-registers and can auto-create itself), point it at a
    /// terrain generator, and it will:
    ///
    ///   1. Discover mod folders and .zip archives under the mods directory.
    ///   2. Parse and validate every mod.json.
    ///   3. Resolve dependency load order.
    ///   4. Apply biome + asset content into the terrain generator.
    ///   5. Log a report and expose results for tooling/UI.
    ///
    /// It runs BEFORE terrain generation so modded biomes are present when the
    /// world bakes. Call GenerateTerrain() (or leave generateOnStartup enabled)
    /// and the modded biomes are part of the world.
    /// </summary>
    [DisallowMultipleComponent]
    [DefaultExecutionOrder(-1000)] // run before terrain generation / other start logic
    public class ModManager : MonoBehaviour
    {
        private static ModManager instance;
        public static ModManager Instance => instance;

        [Header("Mod Sources")]
        [Tooltip("Folder scanned for mods. Empty = <persistentDataPath>/Mods.")]
        public string modsDirectoryOverride;

        [Tooltip("Also scan Unity's StreamingAssets/Mods folder (ships with the build).")]
        public bool includeStreamingAssetsMods = true;

        [Header("Loading")]
        [Tooltip("Discover, parse, and apply mods automatically on Awake.")]
        public bool loadOnStartup = true;

        [Tooltip("Generate terrain immediately after mods load so modded biomes appear in the world.")]
        public bool generateTerrainAfterLoad = true;

        [Tooltip("Write a modload_report.txt next to the mods folder after loading.")]
        public bool writeReportFile = true;

        [Header("References")]
        [Tooltip("Terrain generator mods are applied to. Auto-found in the scene if left empty.")]
        public HomesteaderTerrainGenerator terrainGenerator;

        [Tooltip("Optional asset resolver (Addressables / AssetBundles / runtime mesh import).")]
        public MonoBehaviour assetResolverBehaviour;

        [Header("Debug")]
        public bool verboseLogging = true;

        /// <summary>All discovered mods, in resolved load order.</summary>
        public readonly List<ModInfo> LoadedMods = new List<ModInfo>();

        /// <summary>Per-mod summaries of what was applied.</summary>
        public readonly List<ModLoadResult> Results = new List<ModLoadResult>();

        /// <summary>True once a load pass has completed (successfully or not).</summary>
        public bool LoadComplete { get; private set; }

        /// <summary>Raised after every load pass; handy for UI refresh.</summary>
        public event Action ModsLoaded;

        private IModAssetResolver assetResolver;

        private void Awake()
        {
            if (instance != null && instance != this)
            {
                Destroy(gameObject);
                return;
            }
            instance = this;

            // Prefer an explicitly assigned resolver; otherwise build the default
            // one, which loads generated prefabs from Resources/Mods. A resolver
            // of null means every asset stays data-only (never spawns a model).
            assetResolver = assetResolverBehaviour as IModAssetResolver ?? BuildDefaultResolver();

            if (loadOnStartup)
                LoadMods();
        }

        /// <summary>
        /// The default asset resolver: prefabs generated by
        /// Tools &gt; Homesteader &gt; Mods &gt; Generate Mod Prefabs, loaded from
        /// Resources/Mods at runtime.
        /// </summary>
        private IModAssetResolver BuildDefaultResolver()
        {
            string modsRoot = string.IsNullOrWhiteSpace(modsDirectoryOverride)
                ? Path.Combine(Application.persistentDataPath, "Mods")
                : modsDirectoryOverride;

            var provider = new ResourcesPrefabProvider(m => Debug.Log(m));
            return new FileAssetResolver(provider, modsRoot, m => Debug.Log(m));
        }

        private void OnDestroy()
        {
            if (instance == this)
                instance = null;
        }

        /// <summary>
        /// Runs a full load pass. Safe to call repeatedly (e.g. an in-game
        /// "Reload Mods" button); each pass re-discovers from disk.
        /// </summary>
        [ContextMenu("Load Mods")]
        public void LoadMods()
        {
            var log = new StringBuilder();
            void Log(string message)
            {
                log.AppendLine(message);
                if (verboseLogging) Debug.Log(message);
            }

            Homesteader.Growth.GrowthRegistry.Clear();
            Homesteader.Growth.GameRules.Clear();
            LoadedMods.Clear();
            Results.Clear();
            LoadComplete = false;

            List<string> roots = CollectModRoots();
            if (roots.Count == 0)
            {
                Log("[Mods] No mods directory found; running with core content only.");
                FinishPass(null, log);
                return;
            }

            foreach (string root in roots)
            {
                Log($"[Mods] Scanning '{root}'");
                List<ModInfo> found = ModDiscovery.Discover(root, Log);
                foreach (ModInfo mod in found)
                    ParseManifest(mod, Log);
                LoadedMods.AddRange(found);
            }

            ModDiscovery.ResolveLoadOrder(LoadedMods, Log);
            LogLoadOrder(Log);
            // (LogLoadOrder takes the log action so its messages land in both the
            // console and the report file.)

            if (terrainGenerator == null)
                terrainGenerator = FindAnyObjectByType<HomesteaderTerrainGenerator>();

            if (terrainGenerator == null)
            {
                // No generated terrain (e.g. a flat-ground scene): biomes and spawnable
                // assets have nowhere to go, but growth groups and item use-behaviours
                // (right-click planting) do not need a terrain, so still apply those.
                Log("[Mods] No HomesteaderTerrainGenerator in the scene; applying growth groups and item behaviours only.");
                Results.AddRange(ModLoader.ApplyAll(LoadedMods, null, assetResolver, Log));
            }
            else
            {
                // Snapshot core counts so the report can show what mods actually added.
                int coreBiomes = terrainGenerator.biomes.Count;
                int coreAssets = terrainGenerator.registeredAssets.Count;

                Results.AddRange(ModLoader.ApplyAll(LoadedMods, terrainGenerator, assetResolver, Log));

                Log($"[Mods] Terrain generator now holds {terrainGenerator.biomes.Count} biomes " +
                    $"({terrainGenerator.biomes.Count - coreBiomes} from mods) and " +
                    $"{terrainGenerator.registeredAssets.Count} spawnable assets " +
                    $"({terrainGenerator.registeredAssets.Count - coreAssets} from mods).");

                if (generateTerrainAfterLoad)
                {
                    Log("[Mods] Regenerating terrain with modded content...");
                    terrainGenerator.GenerateTerrain();
                }
            }

            FinishPass(roots[0], log);
        }

        // ------------------------------------------------------------- Internals

        private void ParseManifest(ModInfo mod, Action<string> log)
        {
            if (mod.Errors.Count > 0)
                return; // discovery already flagged it (e.g. bad zip)

            string manifestPath = Path.Combine(mod.RootPath, ModManifestParser.ManifestFileNameFor);
            if (!File.Exists(manifestPath))
            {
                mod.Errors.Add($"No {ModManifestParser.ManifestFileNameFor} found in '{mod.SourceName}'.");
                return;
            }

            string text;
            try
            {
                text = File.ReadAllText(manifestPath);
            }
            catch (Exception ex)
            {
                mod.Errors.Add($"Could not read {ModManifestParser.ManifestFileNameFor}: {ex.Message}");
                return;
            }

            mod.Manifest = ModManifestParser.Parse(text, manifestPath, mod);
            if (mod.Manifest != null && string.IsNullOrEmpty(mod.Category))
            {
                string cat = mod.Manifest.Raw.Get("category").AsString();
                if (string.IsNullOrEmpty(cat)) cat = mod.Manifest.Raw.Get("namespace").AsString();
                if (string.IsNullOrEmpty(cat) && mod.Manifest.Contents.Count > 0)
                {
                    cat = mod.Manifest.Contents[0].Group;
                    if (string.IsNullOrEmpty(cat)) cat = mod.Manifest.Contents[0].Type;
                }
                if (!string.IsNullOrEmpty(cat))
                {
                    mod.Category = char.ToUpperInvariant(cat[0]) + cat.Substring(1);
                }
                else
                {
                    mod.Category = "General";
                }
            }
        }

        private List<string> CollectModRoots()
        {
            var roots = new List<string>();
            var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

            void AddRoot(string path)
            {
                if (string.IsNullOrWhiteSpace(path)) return;
                try
                {
                    string full = Path.GetFullPath(path);
                    if (seen.Add(full) && Directory.Exists(full))
                        roots.Add(full);
                }
                catch { }
            }

            string main = string.IsNullOrWhiteSpace(modsDirectoryOverride)
                ? Path.Combine(Application.persistentDataPath, "Mods")
                : modsDirectoryOverride;

            if (!Directory.Exists(main))
            {
                try { Directory.CreateDirectory(main); } catch { }
            }
            AddRoot(main);

            if (includeStreamingAssetsMods)
            {
                AddRoot(Path.Combine(Application.streamingAssetsPath, "Mods"));
            }

            // Also check Assets/Mods in project
            AddRoot(Path.Combine(Application.dataPath, "Mods"));

            // Also check dev repo root mods/
            try
            {
                AddRoot(Path.GetFullPath(Path.Combine(Application.dataPath, "../../mods")));
                AddRoot(Path.Combine(Directory.GetCurrentDirectory(), "mods"));
            }
            catch { }

            return roots;
        }

        private void LogLoadOrder(Action<string> log)
        {
            int valid = 0;
            int disabled = 0;
            foreach (ModInfo mod in LoadedMods)
            {
                if (mod.IsDisabled) disabled++;
                else if (mod.IsValid) valid++;

                foreach (string warning in mod.Warnings)
                    log($"[Mods] WARN {mod.SourceName}: {warning}");

                foreach (string error in mod.Errors)
                    log($"[Mods] ERROR {mod.SourceName}: {error}");
            }

            log($"[Mods] Discovered {LoadedMods.Count} source(s) ({disabled} disabled); {valid} active.");
        }

        private void FinishPass(string reportRoot, StringBuilder log)
        {
            LoadComplete = true;

            if (writeReportFile && !string.IsNullOrEmpty(reportRoot))
            {
                try
                {
                    string reportPath = Path.Combine(reportRoot, "modload_report.txt");
                    File.WriteAllText(reportPath, BuildReport(log));
                    if (verboseLogging)
                        Debug.Log($"[Mods] Wrote load report to {reportPath}");
                }
                catch (Exception ex)
                {
                    Debug.LogWarning($"[Mods] Could not write load report: {ex.Message}");
                }
            }

            ModsLoaded?.Invoke();
        }

        private string BuildReport(StringBuilder log)
        {
            var sb = new StringBuilder();
            sb.AppendLine("Homesteader mod load report");
            sb.AppendLine($"Generated: {DateTime.Now:yyyy-MM-dd HH:mm:ss}");
            sb.AppendLine(new string('-', 60));

            foreach (ModInfo mod in LoadedMods)
            {
                if (mod.IsDisabled)
                    sb.AppendLine($"DISABLED {mod.Manifest?.Name ?? mod.SourceName} ({mod.SourceName})");
                else if (mod.IsValid)
                    sb.AppendLine($"LOADED  {mod.Manifest}");
                else
                    sb.AppendLine($"FAILED  {mod.SourceName}");
                if (mod.IsValid && mod.Manifest.Description != null)
                    sb.AppendLine($"        {mod.Manifest.Description}");

                foreach (string w in mod.Warnings) sb.AppendLine($"        WARN  {w}");
                foreach (string e in mod.Errors) sb.AppendLine($"        ERROR {e}");
            }

            sb.AppendLine(new string('-', 60));
            foreach (ModLoadResult result in Results)
                sb.AppendLine($"APPLIED {result.Summary}");

            sb.AppendLine(new string('-', 60));
            sb.AppendLine("Log:");
            sb.Append(log);

            return sb.ToString();
        }

        /// <summary>Convenience accessor: every loaded mod that declared the given content type.</summary>
        public IEnumerable<ModInfo> ModsProviding(string contentType)
        {
            foreach (ModInfo mod in LoadedMods)
            {
                if (!mod.IsValid) continue;
                foreach (ModContentEntry entry in mod.Manifest.Contents)
                {
                    if (string.Equals(entry.Type, contentType, StringComparison.OrdinalIgnoreCase))
                    {
                        yield return mod;
                        break;
                    }
                }
            }
        }

        /// <summary>Total modded biomes currently registered on the terrain generator.</summary>
        public int ModdedBiomeCount
        {
            get
            {
                int count = 0;
                foreach (ModLoadResult r in Results) count += r.BiomesAdded;
                return count;
            }
        }
    }
}
